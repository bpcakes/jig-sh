fn resolve_bind_addr(
    host: Option<&str>,
    port: Option<&str>,
    configured_bind_addr: Option<&str>,
) -> Result<SocketAddr> {
    if let (Some(host), Some(port)) = (
        host.filter(|value| !value.is_empty()),
        port.filter(|value| !value.is_empty()),
    ) {
        let host = host
            .parse::<IpAddr>()
            .with_context(|| format!("Failed to parse HOST '{host}' as an IP address"))?;
        let port = port
            .parse::<u16>()
            .with_context(|| format!("Failed to parse PORT '{port}' as a TCP port"))?;
        return Ok(SocketAddr::new(host, port));
    }

    let bind_addr = configured_bind_addr.unwrap_or("127.0.0.1:0");
    bind_addr
        .parse()
        .with_context(|| format!("Failed to parse BIND_ADDR '{bind_addr}' as a socket address"))
}

