#[derive(Clone, Copy, Debug, Eq, PartialEq)]
struct SqliteDatabaseUrlSemantics {
    in_memory: bool,
    shared_cache: bool,
}

impl SqliteDatabaseUrlSemantics {
    fn requires_single_connection_pool(self) -> bool {
        self.in_memory && !self.shared_cache
    }
}

fn sqlite_database_url_is_in_memory(database_url: &str) -> bool {
    sqlite_database_url_semantics(database_url).in_memory
}

fn sqlite_database_url_semantics(database_url: &str) -> SqliteDatabaseUrlSemantics {
    let database_and_params = database_url
        .trim_start_matches("sqlite://")
        .trim_start_matches("sqlite:");
    let (database, params) = database_and_params
        .split_once('?')
        .map_or((database_and_params, None), |(database, params)| {
            (database, Some(params))
        });
    let in_memory = database == ":memory:";
    let mut semantics = SqliteDatabaseUrlSemantics {
        in_memory,
        shared_cache: in_memory,
    };

    if let Some(params) = params {
        // Keep this ordered update behavior aligned with SQLx 0.8.6. In
        // particular, a later `mode=memory` re-enables shared cache while a
        // later `cache=private` disables it again.
        for (key, value) in url::form_urlencoded::parse(params.as_bytes()) {
            match (key.as_ref(), value.as_ref()) {
                ("mode", "memory") => {
                    semantics.in_memory = true;
                    semantics.shared_cache = true;
                }
                ("cache", "private") => semantics.shared_cache = false,
                ("cache", "shared") => semantics.shared_cache = true,
                _ => {}
            }
        }
    }

    semantics
}

